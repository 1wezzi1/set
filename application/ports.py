from typing import Protocol
from uuid import UUID

from domain.entities import Debt, User


class UserRepository(Protocol):
    def add(self, user: User) -> None: ...
    def get(self, user_id: UUID) -> User | None: ...
    def all(self) -> list[User]: ...


class DebtRepository(Protocol):
    def add(self, debt: Debt) -> None: ...
    def all(self) -> list[Debt]: ...
    def replace_all(self, debts: list[Debt]) -> None: ...


class UnitOfWork(Protocol):
    users: UserRepository
    debts: DebtRepository

    def __enter__(self) -> "UnitOfWork": ...
    def __exit__(self, exc_type, exc, tb) -> None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...


class UnitOfWorkFactory(Protocol):
    """Фабрика UoW — чтобы presentation не знал про SqlUnitOfWork."""

    def __call__(self) -> UnitOfWork: ...